#!/usr/bin/env python3
"""Subset the Material Symbols icon font to the icons the frontend uses.

The full variable font in the `material-symbols` package is ~4 MB (4,000+ icons); Vertex uses a few hundred, and the
subset is ~200 KB. Icons are drawn by ligature (`<span className="ms">flight</span>`), so the subset keeps the glyph for
each used name plus the letters that spell it, and drops every other ligature. All variation axes are kept (FILL for
`.ms-fill`, weight, optical size, grade).

A name counts as used when it appears in frontend/src as a quoted string ('flight', "flight", `flight`) or as JSX text
(>flight<) and is an icon in the font. Unrelated words that happen to be icon names are included too: harmless.

    # regenerate after adding an icon or bumping material-symbols (needs fonttools and brotli):
    docker run --rm -v "$PWD:/w" -w /w python:3.12-slim sh -c \
      'pip install -q fonttools==4.69.1 brotli==1.2.1 && python scripts/subset_icons.py'

    # CI: fail when the source uses an icon that the subset lacks (standard library only; needs frontend/node_modules)
    python3 scripts/subset_icons.py --check
"""
from __future__ import annotations

import argparse
import io
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "frontend"
PACKAGE = FRONTEND / "node_modules" / "material-symbols"
SOURCE_FONT = PACKAGE / "material-symbols-outlined.woff2"
OUT_DIR = FRONTEND / "src" / "assets" / "fonts"
OUT_FONT = OUT_DIR / "material-symbols-outlined.subset.woff2"
MANIFEST = OUT_DIR / "material-symbols-icons.json"

_QUOTED = re.compile(r"""['"`]([a-z0-9_]+)['"`]""")
_JSX_TEXT = re.compile(r">\s*([a-z0-9_]+)\s*<")


def referenced_words() -> set[str]:
    words: set[str] = set()
    for path in (FRONTEND / "src").rglob("*"):
        if path.suffix in (".ts", ".tsx", ".css") and path.is_file():
            text = path.read_text(errors="ignore")
            words.update(_QUOTED.findall(text))
            words.update(_JSX_TEXT.findall(text))
    return words


def package_version() -> str:
    return json.loads((PACKAGE / "package.json").read_text())["version"]


def package_icon_names() -> set[str]:
    """Icon names the package lists (index.d.ts); the font also has a few hundred aliases on top of these."""
    return set(re.findall(r'"([a-z0-9_]+)"', (PACKAGE / "index.d.ts").read_text()))


def font_ligatures(font) -> dict[str, str]:
    """Icon name -> glyph name, read from the font's ligature table."""
    reverse = {glyph: chr(code) for code, glyph in font.getBestCmap().items()}
    names: dict[str, str] = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            sub = getattr(sub, "ExtSubTable", sub)
            for first, ligatures in getattr(sub, "ligatures", {}).items():
                for lig in ligatures:
                    try:
                        names["".join(reverse[g] for g in [first, *lig.Component])] = lig.LigGlyph
                    except KeyError:
                        continue
    return names


def generate() -> int:
    from fontTools import subset
    from fontTools.ttLib import TTFont

    font = TTFont(str(SOURCE_FONT))
    ligatures = font_ligatures(font)
    icons = sorted(referenced_words() & ligatures.keys())

    options = subset.Options()
    options.flavor = "woff2"
    options.layout_closure = False          # keep only the ligatures whose glyphs are kept, not all 4,000
    options.layout_features = ["liga", "rlig", "calt", "ccmp"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(glyphs=[ligatures[i] for i in icons], unicodes=sorted({ord(c) for c in "".join(icons)}))
    subsetter.subset(font)

    buf = io.BytesIO()
    font.save(buf)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FONT.write_bytes(buf.getvalue())
    MANIFEST.write_text(json.dumps({
        "comment": "Generated by scripts/subset_icons.py; do not edit.",
        "material_symbols_version": package_version(),
        "icons": icons,
    }, indent=1) + "\n")
    print(f"{len(icons)} icons, {len(buf.getvalue()) // 1024} KB (from {SOURCE_FONT.stat().st_size // 1024} KB)"
          f" -> {OUT_FONT.relative_to(ROOT)}")
    return 0


def check() -> int:
    manifest = json.loads(MANIFEST.read_text())
    problems = []
    if manifest["material_symbols_version"] != package_version():
        problems.append(f"material-symbols is {package_version()} but the subset was built from "
                        f"{manifest['material_symbols_version']}")
    missing = sorted((referenced_words() & package_icon_names()) - set(manifest["icons"]))
    if missing:
        problems.append("icons used in frontend/src but missing from the subset font: " + ", ".join(missing))
    if problems:
        for p in problems:
            print("error:", p, file=sys.stderr)
        print("Regenerate: see the docker command at the top of scripts/subset_icons.py, and commit both files.",
              file=sys.stderr)
        return 1
    print(f"icon font subset is current ({len(manifest['icons'])} icons)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="verify the committed subset covers the source")
    return check() if parser.parse_args().check else generate()


if __name__ == "__main__":
    sys.exit(main())
